#!/usr/bin/env node
/**
 * Génère un fichier d’ignore Trivy daté depuis security/exceptions.json.
 * Ne pas committer de .trivyignore figé : chaque CVE doit avoir expiry + compensation.
 */
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadExceptions } from './audit-dependencies.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');

export function idsForScanner(exceptions, scanner) {
  return exceptions
    .filter((item) => item.scanner === scanner)
    .map((item) => String(item.id ?? '').trim())
    .filter(Boolean);
}

export function renderTrivyIgnore(exceptions, scanner) {
  const ids = idsForScanner(exceptions, scanner);
  return [
    '# Generated by scripts/generate-trivy-ignore.mjs from security/exceptions.json.',
    '# Do not edit by hand; expired entries fail scripts/check-exceptions.mjs.',
    '',
    ...ids,
    '',
  ].join('\n');
}

if (process.argv[1]?.endsWith('generate-trivy-ignore.mjs')) {
  const scanner = process.argv[2] ?? 'trivy-image-os';
  const outPath = process.argv[3] ?? join(ROOT, '.trivyignore.generated');
  const { exceptions } = loadExceptions();
  const ids = idsForScanner(exceptions, scanner);
  writeFileSync(outPath, renderTrivyIgnore(exceptions, scanner), 'utf8');
  console.log(`Wrote ${ids.length} ${scanner} exception(s) to ${outPath}`);
}
